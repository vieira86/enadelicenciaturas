export function getQuestionById(id: string): Question | undefined {
  return questions.find((q) => q.id === id)
}

export function getQuestionsByModule(moduleId: string): Question[] {
  return questions.filter((q) => q.moduleId === moduleId)
}

export function getFlashcardsByModule(moduleId: string): Flashcard[] {
  return flashcards.filter((f) => f.moduleId === moduleId)
}

export function getRandomQuestions(count: number): Question[] {
  const shuffled = [...questions].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}
